#include<stdio.h>
int main()
{ 
    printf("int  => %zu\n", sizeof(int));  // printing size of int
    printf("char => %zu\n", sizeof(char));  // printing size of char
    printf("float => %zu\n", sizeof(float));  // printing size of float
    printf("double => %zu\n", sizeof(double));  // printing size of double
    return 0;
}